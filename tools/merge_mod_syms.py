#!/usr/bin/env python3
"""Merge N64Recomp --dump-context function dumps for code mods.

Each dump is an independent TOML file made only of `[[section]]` blocks.  A code
mod needs one reference file that contains the main ELF plus the separately
linked streamed-bank ELFs, so concatenate those blocks while keeping a short
provenance comment for diagnostics.

Usage:
    tools/merge_mod_syms.py OUTPUT INPUT [INPUT ...]
"""

from __future__ import annotations

import argparse
from pathlib import Path


def section_count(text: str) -> int:
    return sum(1 for line in text.splitlines() if line.strip() == "[[section]]")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("inputs", nargs="+", type=Path)
    args = parser.parse_args()

    chunks: list[str] = ["# Autogenerated merged N64Recomp function context.\n"]
    total_sections = 0

    for path in args.inputs:
        if not path.is_file():
            parser.error(f"missing input: {path}")
        text = path.read_text()
        count = section_count(text)
        if count == 0:
            parser.error(f"{path}: no [[section]] blocks")
        total_sections += count

        # Drop only the standard generated-file comment. Repeated TOML comments
        # are legal, but the merged file is easier to inspect with one provenance
        # marker per source instead.
        lines = text.splitlines()
        if lines and lines[0].startswith("# Autogenerated"):
            lines = lines[1:]
        body = "\n".join(lines).strip()
        chunks.append(f"\n# source: {path.as_posix()}\n{body}\n")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(chunks))
    print(
        f"merged {len(args.inputs)} dump(s), {total_sections} section(s) -> "
        f"{args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
